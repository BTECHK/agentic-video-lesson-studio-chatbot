/**
 * Corpus ledger — the anti-"partial count reported as done" artifact.
 *
 *   npm run corpus:ledger
 *
 * Enumerates EVERY course lesson (topic-* + bonus-*), reads its five gate
 * artifacts, and prints one row per lesson plus an N/N summary. Writes the
 * same table to .planning/CORPUS-LEDGER.md. Exits 0 only when every lesson
 * is fully green — so "review complete" is a printed N/N count, never a
 * narrative claim. Any non-corpus lesson ids are listed but excluded from the launch
 * corpus count (no narration alignment yet).
 */
import fs from 'node:fs';
import path from 'node:path';
import { runMain } from '../src/lib/logger';
import { summarizeGates, canPublish, GATES } from '../src/lib/gate-status';
import { corpusLessonIds, ledgerRow, type LedgerEntry } from '../src/lib/corpus-ledger';

runMain('corpus:ledger', async (log) => {
  const lessonsRoot = path.join(process.cwd(), 'content', 'lessons');
  const { corpus, extra } = corpusLessonIds(fs.readdirSync(lessonsRoot));

  const entries: LedgerEntry[] = corpus.map((id) => {
    const dir = path.join(lessonsRoot, id);
    const read = (rel: string): string | null => {
      const p = path.join(dir, rel);
      return fs.existsSync(p) ? fs.readFileSync(p, 'utf-8') : null;
    };
    const summary = summarizeGates(
      id,
      Object.fromEntries(GATES.map((g) => [g.gate, read(g.artifact)])) as Parameters<typeof summarizeGates>[1],
    );
    return { id, gates: summary.gates.map((g) => ({ gate: g.gate, state: g.state })), ok: canPublish(summary).ok };
  });

  const green = entries.filter((e) => e.ok);
  const lines = entries.map((e) => ledgerRow(e));
  for (const l of lines) log.info(l);
  log.info(`CORPUS: ${green.length}/${entries.length} lessons fully green (A·B·C·L·T)`);
  if (extra.length > 0) log.info(`excluded from corpus count: ${extra.join(', ')}`);

  const md = [
    '# Corpus Ledger — per-lesson gate state',
    '',
    `Generated by \`npm run corpus:ledger\` on ${new Date().toISOString()}.`,
    'A "review complete" claim is valid ONLY as the N/N count below — never as prose.',
    '',
    '```',
    ...lines,
    `CORPUS: ${green.length}/${entries.length} lessons fully green (A·B·C·L·T)`,
    '```',
    '',
    extra.length > 0 ? `Excluded (not in launch corpus): ${extra.join(', ')}` : '',
  ].join('\n');
  fs.writeFileSync(path.join(process.cwd(), '.planning', 'CORPUS-LEDGER.md'), md);

  return green.length === entries.length ? 0 : 1;
});
